import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { Noir } from '@noir-lang/noir_js';
import { encodeAbiParameters, keccak256 } from 'viem';
import { dictionaryWitness, dictionaryPublicInputs } from '../web/proof-inputs.ts';
import { Barretenberg, BackendType, UltraHonkBackend } from '@aztec-foundation/bb.js';
const circuitBytes = await readFile('artifacts/dictionary-circuit.json');
const circuit = JSON.parse(circuitBytes);
const dictionary = JSON.parse(await readFile('dictionary/tree-manifest.json', 'utf8'));
const bb = await Barretenberg.new({ backend: BackendType.Wasm, threads: 1 });
const options = { verifierTarget: 'evm' }; // Includes zero-knowledge masking.
try {
  const backend = new UltraHonkBackend(circuit.bytecode, bb);
  const vk = await backend.getVerificationKey(options);
  const verifier = await backend.getSolidityVerifier(vk, options);
  // Derive the accepted proof length from this exact circuit/backend, using
  // public synthetic inputs. Never infer it from an older circuit's size.
  const words = (await readFile('dictionary/words.txt', 'utf8')).trimEnd().split('\n');
  const tree = await readFile('public/zk/dictionary-tree.bin');
  const recovery = { version: 1, chainId: 31337,
    contract: '0x1111111111111111111111111111111111111111',
    creator: '0x2222222222222222222222222222222222222222',
    word: words.find(word => word.length === dictionary.maxWordLength), salt: '0x' + 'ab'.repeat(32) };
  recovery.commitment = keccak256(encodeAbiParameters(
    [{type:'uint256'}, {type:'address'}, {type:'address'}, {type:'string'}, {type:'bytes32'}],
    [31337n, recovery.contract, recovery.creator, recovery.word, recovery.salt]));
  const { witness } = await new Noir(circuit).execute(dictionaryWitness(recovery, words, tree, dictionary.root));
  const sample = await backend.generateProof(witness, options);
  assert.deepEqual(sample.publicInputs.map(x => x.toLowerCase()), dictionaryPublicInputs(recovery, dictionary.root));
  assert.equal(await backend.verifyProof(sample, options), true);
  const proofBytes = sample.proof.length;
  witness.fill(0);
  await mkdir('contracts-v2/generated', { recursive: true });
  await mkdir('public/zk', { recursive: true });
  await mkdir('web/generated', { recursive: true });
  await writeFile('contracts-v2/generated/DictionaryVerifier.sol', verifier);
  await writeFile('contracts-v2/generated/DictionaryConfig.sol', `// SPDX-License-Identifier: MIT\npragma solidity ^0.8.38;\n\n// Generated by npm run proof:build. Do not edit.\nlibrary DictionaryConfig {\n    uint8 internal constant MAX_WORD_LENGTH = ${dictionary.maxWordLength};\n    uint256 internal constant PROOF_BYTES = ${proofBytes};\n}\n`);
  await writeFile('artifacts/dictionary-vk.bin', vk);
  await copyFile('artifacts/dictionary-circuit.json', 'public/zk/dictionary-circuit.json');
  const sha256 = value => createHash('sha256').update(value).digest('hex');
  const manifest = {
    schemaVersion: 2, maxWordLength: dictionary.maxWordLength, depth: dictionary.depth, root: dictionary.root, dictionaryId: dictionary.dictionaryId,
    circuitSha256: sha256(circuitBytes), wordsSha256: dictionary.wordsSha256,
    treeSha256: dictionary.treeSha256, verificationKeySha256: sha256(vk),
    verifierSourceSha256: sha256(verifier), noirVersion: '1.0.0', backendVersion: '6.0.0',
    verifierTarget: 'evm', publicInputCount: 8, proofBytes,
  };
  await writeFile('public/zk/prover-manifest.json', JSON.stringify(manifest, null, 2)+'\n');
  await writeFile('web/generated/proverManifest.ts', '// Generated by npm run proof:build. Do not edit.\nexport const proverManifest = '+JSON.stringify(manifest,null,2)+' as const;\n');
  await writeFile('dictionary/prover-manifest.json', JSON.stringify(manifest,null,2)+'\n');
  console.log(`Generated zero-knowledge EVM verifier and pinned proving assets for ${dictionary.dictionaryId}`);
} finally { await bb.destroy(); }
