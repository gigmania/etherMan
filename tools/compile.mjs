import { readFile, writeFile, mkdir } from "node:fs/promises";
import solc from "solc";

const compiler = solc.version();
if (!compiler.startsWith("0.8.38+"))
  throw new Error(`Expected solc 0.8.38, got ${compiler}`);
const source = await readFile("contracts-v2/EtherMan.sol", "utf8");
const input = {
  language: "Solidity",
  sources: { "contracts-v2/EtherMan.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: {
      "*": {
        "*": [
          "abi",
          "evm.bytecode.object",
          "evm.deployedBytecode.object",
          "metadata",
        ],
      },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const error of output.errors ?? []) console.error(error.formattedMessage);
if (output.errors?.some((error) => error.severity === "error")) process.exit(1);
const contract = output.contracts["contracts-v2/EtherMan.sol"].EtherMan;
const artifact = {
  contractName: "EtherMan",
  compiler,
  abi: contract.abi,
  bytecode: `0x${contract.evm.bytecode.object}`,
  deployedBytecode: `0x${contract.evm.deployedBytecode.object}`,
  metadata: JSON.parse(contract.metadata),
};
await mkdir("artifacts", { recursive: true });
await mkdir("web/generated", { recursive: true });
await writeFile(
  "artifacts/EtherMan.json",
  JSON.stringify(artifact, null, 2) + "\n",
);
await writeFile(
  "web/generated/etherManAbi.ts",
  "// Generated by npm run contracts:build. Do not edit.\nexport const etherManAbi = " +
    JSON.stringify(contract.abi, null, 2) +
    " as const\n",
);
console.log(
  `Compiled EtherMan with ${compiler}; runtime ${contract.evm.deployedBytecode.object.length / 2} bytes.`,
);
